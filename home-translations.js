// Merge into the shared translations object (exposed by script.js) and re-apply.
document.addEventListener('DOMContentLoaded', () => {
  const t = window.translations;
  if (!t) return;

  Object.keys(homeTranslationsExtended).forEach(lang => {
    if (t[lang]) {
      Object.assign(t[lang], homeTranslationsExtended[lang]);
    }
  });

  let lang = localStorage.getItem('petnudge-lang') ||
             navigator.language.split('-')[0] ||
             'fr';
  if (!t[lang]) lang = 'en';

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[lang] && t[lang][key]) {
      el.textContent = t[lang][key];
    }
  });
});
